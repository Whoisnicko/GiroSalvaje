const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const read=p=>fs.readFileSync(path.join(__dirname,'../',p),'utf8');
const game=read('engine/game.js'),start=game.indexOf('const KIND = {'),end=game.indexOf('\n',game.indexOf('function pickKind(table)'));
const c=vm.createContext({WORLD_H:260,WALL_X:40,MAX_WAVE:10,worldW:()=>1000,rnd:(a,b)=>(a+b)/2,spellEnemyRooted:e=>!!e.root,infusionHidden:()=>false,S:{biomeId:'forest',charge:false}});
vm.runInContext(read('engine/biomes-bosses.js')+'\n'+game.slice(start,end),c);
const run=s=>vm.runInContext(s,c);
assert.ok(run("Array.from({length:10},(_,i)=>i+1).every(w=>{const q=rollWave(w,'valley');return !q.some(e=>regionalDef(e))&&q.length===waveInfo(w).n+(w%5===0?1:0)})"));
assert.ok(run("Array.from({length:5},(_,i)=>i+1).every(w=>{const q=rollWave(w,'forest');return Object.entries(REGIONAL_ENEMIES).every(([id,d])=>q.filter(e=>e.kind===id).length===d.counts[w-1])&&q.length===waveInfo(w).n+(w===5?1:0)})"));
assert.equal(run("rollWave(5,'forest').find(e=>e.boss).bossId"),'huntsman');
assert.equal(run("biomeWalkFactor({kind:'pathfinder',x:430,y:163.8})"),1);
assert.equal(run("biomeWalkFactor({x:430,y:163.8})"),.7);
assert.equal(run("regionalShotFactor({}, {x:240,y:75.4})"),.75);
assert.equal(run("regionalShotFactor({ignoreCover:true},{x:240,y:75.4})"),1);
run("const r={kind:'ranger',x:340,y:80,range:150},u={x:140,y:80,hp:100}");
assert.equal(run("regionalRangerCover(r,[u],null,1000).kind"),'cover');
assert.equal(run("regionalRangerCover({...r,root:1},[u],null,1000)"),null);
assert.equal(run("regionalRangerCover(r,[u],u,1000)"),null);
assert.equal(run("S.charge=true;regionalRangerCover(r,[u],null,1000)"),null);
assert.equal(run("regionalEnemyAllowed('ranger','valley')"),false);
assert.equal(run("enemyRanged({kind:'purifier'})"),true);
assert.ok(game.includes('regionalShotFactor(s,s.tgt)'));assert.ok(game.includes('regionalRangerCover(e,targets,forcedHero,Wd)'));
console.log('Regional enemy rules, wave distribution and Valley isolation OK');
